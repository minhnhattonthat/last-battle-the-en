"""gen_jp_tbl.py: generate tbl/jp.tbl from the verified font order (docs/re/text.md).

Text is 16-bit little-endian words, so table keys are the two bytes as stored (0x0335 -> key 3503).
Glyph code = $0300 + font index; the font is a JIS-X-0208-ordered SUBSET (only characters the game uses), so
every range here was checked against tools/re_glyphs.py sheets and decoded strings. Katakana and kanji
($0384-$07D0) are not identified yet: phase 4 matches them against a JIS-ordered reference font."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SYMBOLS = {  # $0300-$030F, read off the glyph sheet (work/re_g5.png)
    0x300: r"\s", 0x301: "。", 0x302: "・", 0x303: "？", 0x304: "！", 0x305: "ヶ", 0x306: "／", 0x307: "～",
    0x308: "「", 0x309: "『", 0x30A: "』", 0x30B: "＋", 0x30C: "－", 0x30D: "{sym30D}", 0x30E: "＊", 0x30F: "⇒",
}
# Hiragana in JIS order without ゎゐゑ ($0382 = を confirmed by 名前を in the name-entry prompt).
HIRAGANA = ("ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねの"
            "はばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろわをん")
CONTROLS = {  # high byte of a word >= $8000; low byte is the argument. Names are provisional (docs/re/text.md).
    0xFE00: "{nl}", 0xFF00: "{end}", 0xFF02: "{end2}",
}


def key(code):
    return code.to_bytes(2, "little").hex().upper()


def main():
    lines = ["# The Last Battle (SFC) Japanese table. Generated by tools/gen_jp_tbl.py; do not edit by hand.",
             "# Keys are the 16-bit LE words as stored. Glyph code = $0300 + font index (font at file 0x107CF3)."]
    for c, v in SYMBOLS.items():
        lines.append(f"{key(c)}={v}")
    for i in range(10):
        lines.append(f"{key(0x310 + i)}={chr(ord('０') + i)}")
    for i in range(26):
        lines.append(f"{key(0x31A + i)}={chr(ord('Ａ') + i)}")
    for i, ch in enumerate(HIRAGANA):
        lines.append(f"{key(0x334 + i)}={ch}")
    for c, v in CONTROLS.items():
        lines.append(f"{key(c)}={v}")
    out = ROOT / "tbl" / "jp.tbl"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out, len(lines) - 2, "entries; last hiragana code", hex(0x334 + len(HIRAGANA) - 1))


if __name__ == "__main__":
    main()
